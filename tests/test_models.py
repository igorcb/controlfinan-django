from datetime import date
from decimal import Decimal

from finance.models import CurrentAccount, User

from .factories import CurrentAccountFactory, UserFactory


class TestUser:
    def test_normalizes_the_email(self):
        user = User(email_address="  Motorista@Exemplo.COM ")
        assert user.validate(password="senha123", password_confirmation="senha123") == []
        assert user.email_address == "motorista@exemplo.com"

    def test_validation_messages_match_the_rails_app(self):
        assert User(email_address="").validate(password="", password_confirmation="", password_required=True) == [
            "Senha não pode ficar em branco",
            "E-mail não pode ficar em branco",
        ]
        assert User(email_address="x").validate() == ["E-mail não é válido"]
        assert User(email_address="x@y.com").validate("123", "456") == [
            "Confirmação da senha não é igual a Senha",
            "Senha é muito curto (mínimo: 6 caracteres)",
        ]

    def test_email_must_be_unique(self, user):
        assert User(email_address="MOTORISTA@exemplo.com").validate() == ["E-mail já está em uso"]

    def test_password_is_stored_as_a_rails_compatible_bcrypt_digest(self, user):
        assert user.password_digest.startswith("$2a$")
        assert user.check_password("senha123")
        assert not user.check_password("errada")

    def test_accepts_a_digest_created_by_rails(self):
        # Digest generated by Rails' has_secure_password for "benchmark123".
        user = UserFactory()
        user.password_digest = "$2a$04$FlbkVcJzCe0FDTDQe20R2eQrFTuzrpaa343pF5pBUqgMBynWnRRyC"
        assert user.check_password("benchmark123")

    def test_authenticate_by(self, user):
        assert User.authenticate_by(" MOTORISTA@exemplo.com", "senha123") == user
        assert User.authenticate_by("motorista@exemplo.com", "errada") is None
        assert User.authenticate_by("ninguem@exemplo.com", "senha123") is None

    def test_password_reset_token_round_trip(self, user):
        assert User.find_by_password_reset_token(user.password_reset_token()) == user
        assert User.find_by_password_reset_token("lixo") is None

    def test_password_reset_token_stops_working_after_a_password_change(self, user):
        token = user.password_reset_token()
        user.set_password("nova-senha")
        user.save()
        assert User.find_by_password_reset_token(token) is None


class TestCurrentAccount:
    def test_validation_messages_match_the_rails_app(self, user):
        entry = CurrentAccount(user=user, cash_account_id=99, cost_id=None, type_launche=None, price=None)
        assert entry.validate() == [
            "Tipo não está incluído na lista",
            "Conta não está incluído na lista",
            "Categoria não está incluído na lista",
            "Data não pode ficar em branco",
            "Valor não pode ficar em branco",
            "Valor não é um número",
        ]

    def test_price_must_be_positive(self, user):
        entry = CurrentAccountFactory.build(user=user, price=Decimal("0"))
        assert entry.validate() == ["Valor deve ser maior que 0"]

    def test_names_and_sign(self):
        credit = CurrentAccountFactory.build(cash_account_id=8, cost_id=6, type_launche=1, price=Decimal("10"))
        debit = CurrentAccountFactory.build(cash_account_id=99, cost_id=99, type_launche=-1, price=Decimal("10"))
        assert (credit.name_account, credit.name_cost, credit.type_launche_name, credit.signed_price) == (
            "99Pop",
            "Corridas",
            "Crédito",
            Decimal("10"),
        )
        assert (debit.name_account, debit.name_cost, debit.type_launche_name, debit.signed_price) == (
            "Não definido",
            "Não definido",
            "Débito",
            Decimal("-10"),
        )

    def test_balance_is_credits_minus_debits(self, user):
        CurrentAccountFactory(user=user, type_launche=1, price=Decimal("150"))
        CurrentAccountFactory(user=user, type_launche=-1, price=Decimal("40.50"))
        assert user.current_accounts.balance() == Decimal("109.50")

    def test_balance_of_nothing_is_zero(self, user):
        assert user.current_accounts.balance() == 0

    def test_balance_by_day_most_recent_first(self, user):
        CurrentAccountFactory(user=user, date_ocurrence=date(2026, 10, 1), price=Decimal("10"))
        CurrentAccountFactory(user=user, date_ocurrence=date(2026, 10, 2), price=Decimal("20"), type_launche=-1)
        assert list(user.current_accounts.balance_by_day().items()) == [
            (date(2026, 10, 2), Decimal("-20")),
            (date(2026, 10, 1), Decimal("10")),
        ]

    def test_in_month_and_rides(self, user):
        CurrentAccountFactory(user=user, date_ocurrence=date(2026, 10, 31), cost_id=6)
        CurrentAccountFactory(user=user, date_ocurrence=date(2026, 11, 1), cost_id=6)
        CurrentAccountFactory(user=user, date_ocurrence=date(2026, 10, 5), cost_id=0)
        october = user.current_accounts.in_month(date(2026, 10, 15))
        assert october.count() == 2
        assert october.rides().count() == 1

    def test_total_by_cost(self, user):
        CurrentAccountFactory(user=user, cost_id=0, type_launche=-1, price=Decimal("50"))
        CurrentAccountFactory(user=user, cost_id=0, type_launche=-1, price=Decimal("30"))
        CurrentAccountFactory(user=user, cost_id=3, type_launche=-1, price=Decimal("20"))
        assert user.current_accounts.total_by_cost([0, 8]) == {0: Decimal("80")}

    def test_ordered_by_date_then_id_desc(self, user):
        older = CurrentAccountFactory(user=user, date_ocurrence=date(2026, 1, 1))
        first = CurrentAccountFactory(user=user, date_ocurrence=date(2026, 2, 1))
        second = CurrentAccountFactory(user=user, date_ocurrence=date(2026, 2, 1))
        assert list(user.current_accounts.ordered()) == [second, first, older]
